export function translateContent(text, lang) {
  if (text == null || text === "") return text;
  if (!lang || lang === "pt") return text;
  const entry = CONTENT[text];
  if (entry?.[lang]) return entry[lang];
  // Fallback: replace known phrases inside longer strings
  let out = String(text);
  for (const [pt, map] of Object.entries(CONTENT)) {
    if (map[lang] && out.includes(pt)) out = out.split(pt).join(map[lang]);
  }
  if (lang === "en") {
    out = out.replace(/Clínica/g, "Clinic").replace(/Clinica/g, "Clinic");
  }
  return out;
}
