const I18nContext = createContext(null);

function interpolate(template, vars = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_, key) => (vars[key] ?? `{${key}}`));
}

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const saved = localStorage.getItem(STORAGE_KEY);
    return LOCALES.some((item) => item.id === saved) ? saved : "pt";
  });

  const setLang = (next) => {
    if (!LOCALES.some((item) => item.id === next)) return;
    setLangState(next);
    localStorage.setItem(STORAGE_KEY, next);
  };

  useEffect(() => {
    const meta = LOCALES.find((item) => item.id === lang);
    document.documentElement.lang = meta?.locale || "pt-BR";
  }, [lang]);

  const value = useMemo(() => {
    const table = dict[lang] || dict.pt;
    const t = (key, vars) => interpolate(table[key] ?? dict.pt[key] ?? key, vars);
    const locale = LOCALES.find((item) => item.id === lang)?.locale || "pt-BR";
    return { lang, setLang, t, locale, languages: LOCALES };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}

export function useT() {
  return useI18n().t;
}

export function LanguageSwitcher({ className = "" }) {
  const { lang, setLang, languages, t } = useI18n();
  return (
    <label className={`lang-switch ${className}`.trim()}>
      <span className="lang-switch-label">{t("lang.label")}</span>
      <select value={lang} onChange={(e) => setLang(e.target.value)} aria-label={t("lang.label")}>
        {languages.map((item) => (
          <option key={item.id} value={item.id}>{item.short} · {item.label}</option>
        ))}
      </select>
    </label>
  );
}

